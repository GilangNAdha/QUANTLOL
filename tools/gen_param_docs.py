#!/usr/bin/env python3
"""Generates docs/PARAMETERS.md from the [Parameter] attributes in src/QuantLOL/Parameters.cs."""
import re, os, collections

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "QuantLOL", "Parameters.cs")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "PARAMETERS.md")

text = open(SRC).read()
pat = re.compile(r'\[Parameter\(\s*"([^"]*)"(.*?)\)\]\s*public\s+([\w<>\.\?]+)\s+(\w+)\s*\{\s*get;\s*set;\s*\}',
                 re.S)
rows = []
for m in pat.finditer(text):
    title, attrs, typ, prop = m.group(1), m.group(2), m.group(3), m.group(4)
    def val(key):
        mm = re.search(key + r'\s*=\s*("([^"]*)"|([^,)]+))', attrs)
        if not mm: return ""
        if mm.group(2) is not None: return mm.group(2).strip()
        return mm.group(3).strip()
    rows.append({"title": title, "prop": prop, "type": typ, "group": val("Group") or "Other",
                 "default": val("DefaultValue"), "min": val("MinValue"), "max": val("MaxValue"),
                 "step": val("Step"), "desc": val("Description")})

groups = collections.OrderedDict()
for r in rows:
    groups.setdefault(r["group"], []).append(r)

L = ["# QuantLOL parameter reference\n",
     "Generated by `tools/gen_param_docs.py` from the `[Parameter]` attributes in "
     "`src/QuantLOL/Parameters.cs`; regenerate after changing a parameter. "
     f"{len(rows)} parameters in {len(groups)} groups.\n",
     "Every parameter is also validated at start-up: out-of-range values stop the bot with a clear "
     "message instead of silently trading a different configuration. Volume is **fixed**: the bot "
     "never resizes, averages up, or martingales.\n"]

for g, items in groups.items():
    L.append("## %s\n" % g)
    L.append("| Parameter | Code property | Type | Default | Range | Description |")
    L.append("|---|---|---|---|---|---|")
    for r in items:
        rng = ""
        if r["min"] or r["max"]:
            rng = "%s .. %s" % (r["min"] or "-inf", r["max"] or "+inf")
            if r["step"]: rng += " (step %s)" % r["step"]
        L.append("| %s | `%s` | %s | `%s` | %s | %s |" % (
            r["title"], r["prop"], r["type"], r["default"] or "-", rng,
            (r["desc"] or "").replace("|", "\\|")))
    L.append("")

L.append("## Enumerations\n")
L.append("| Enum | Values | Meaning |")
L.append("|---|---|---|")
L.append("| `EntryTimeFrameOption` | M1, M3, M5, M15 | Setup/confirmation timeframe. Context always uses M15. |")
L.append("| `TargetModeOption` | StructuralWithFallback, StructuralOnly | Whether a synthetic 2R target is allowed when structure offers nothing beyond the minimum R:R. |")
L.append("| `StalePolicyOption` | BlockEntries, WarnAndIgnore | What happens when optional external data (GEX/VIX) is stale. |")
L.append("| `LogVerbosityOption` | Minimal, Normal, Verbose | Log detail. Nothing is logged per tick at Minimal/Normal. |")
L.append("")
L.append("## Safety-critical parameters\n")
L.append("`Lots`, `MaxRiskPerTradeUsd`, `DailyLossLimitUsd`, `EquityDrawdownLimitUsd`, `MaxOpenPositions`, "
         "`MinRewardRisk`, `EnforceRiskCap`, `RejectIfSpecUnverified`, and `RequireExternalData` change what "
         "the bot is allowed to do. Changing them changes the risk mandate described in `docs/BUILD.md`; "
         "do not loosen them to make a backtest look better.\n")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(L))
print("wrote", OUT, "with", len(rows), "parameters in", len(groups), "groups")
for g, items in groups.items():
    print("  ", g, len(items))
